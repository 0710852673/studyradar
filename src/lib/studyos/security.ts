import { supabase } from "@/integrations/supabase/client";

export type SecuritySeverity = "info" | "warning" | "critical";
const SECURITY_EVENT_KINDS = new Set(["sign_in_failed", "google_sign_in_failed"]);

export function sanitizeSecurityEvent(input: {
  kind: string;
  severity?: SecuritySeverity;
  email?: string | null;
  detail?: string;
}) {
  if (!SECURITY_EVENT_KINDS.has(input.kind)) return null;
  const email = input.email?.trim().toLowerCase() ?? "";
  return {
    kind: input.kind,
    severity: input.severity === "critical" || input.severity === "warning" ? input.severity : "info" as SecuritySeverity,
    email: email && email.length <= 254 ? email : null,
    detail: input.detail?.replace(/[\u0000-\u001f\u007f]/g, " ").trim().slice(0, 160) || null,
  };
}

/**
 * Best-effort client event logger. The database trigger independently validates
 * event types, binds user_id to auth.uid(), and rate-limits writes.
 */
export async function logSecurityEvent(
  kind: string,
  opts: { severity?: SecuritySeverity; email?: string | null; detail?: string; userId?: string | null } = {},
) {
  const event = sanitizeSecurityEvent({ kind, ...opts });
  if (!event) return;
  try {
    await supabase.from("security_events").insert({
      ...event,
      user_agent: typeof navigator === "undefined" ? null : navigator.userAgent.slice(0, 200),
      path: typeof window === "undefined" ? null : window.location.pathname.slice(0, 200),
    } as never);
  } catch {
    /* never surface logging failures to the student */
  }
}

// Versioned to reject legacy consent silently generated by Google sign-in.
const CONSENT_KEY = "sr_terms_consent_affirmed_v2";

export function rememberConsent() {
  try {
    sessionStorage.setItem(CONSENT_KEY, new Date().toISOString());
  } catch {
    /* storage disabled */
  }
}

export async function syncConsent(userId: string, alreadyAccepted: boolean) {
  let when: string | null = null;
  try {
    when = sessionStorage.getItem(CONSENT_KEY);
  } catch {
    /* storage disabled */
  }
  if (!when) return;
  if (alreadyAccepted || !Number.isFinite(Date.parse(when)) || Date.now() - Date.parse(when) > 30 * 60_000) {
    sessionStorage.removeItem(CONSENT_KEY);
    return;
  }
  const { error } = await supabase
    .from("profiles")
    .update({ terms_accepted_at: when } as never)
    .eq("id", userId);
  try {
    if (!error) sessionStorage.removeItem(CONSENT_KEY);
  } catch {
    /* ignore */
  }
}
